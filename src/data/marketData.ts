// Helper to generate dynamic realistic chart points for selected timeframe
export function generateChartPoints(basePrice: number, timeframe: string, changePercent: number): CandlePoint[] {
  let count = 24;
  let interval = '15m';

  switch (timeframe) {
    case '1D':
      count = 26;
      interval = '15m';
      break;
    case '5D':
      count = 35;
      interval = '1h';
      break;
    case '1M':
      count = 30;
      interval = '1D';
      break;
    case '6M':
      count = 40;
      interval = '1W';
      break;
    case '1Y':
      count = 52;
      interval = '1W';
      break;
    case 'ALL':
      count = 60;
      interval = '1M';
      break;
    default:
      count = 26;
  }

  const isUp = changePercent >= 0;
  const startPrice = basePrice * (1 - (changePercent / 100));
  const points: CandlePoint[] = [];

  let currentClose = startPrice;
  const step = (basePrice - startPrice) / count;

  for (let i = 0; i < count; i++) {
    const progress = i / count;
    // Add realistic random walk oscillation
    const noise = (Math.sin(i * 0.8) + Math.cos(i * 1.4) * 0.5) * (basePrice * 0.006);
    const expected = startPrice + step * i;
    const open = i === 0 ? startPrice : currentClose;
    let close = expected + noise;

    // ensure final point matches basePrice
    if (i === count - 1) {
      close = basePrice;
    }

    const high = Math.max(open, close) + Math.abs(noise * 0.8) + (basePrice * 0.002);
    const low = Math.min(open, close) - Math.abs(noise * 0.8) - (basePrice * 0.002);
    const volume = Math.floor(100000 + Math.random() * 500000 + (progress > 0.8 ? 300000 : 0));

    let timeStr = `${9 + Math.floor(i / 4)}:${(i % 4) * 15 || '00'}`;
    if (timeframe === '1M' || timeframe === '6M' || timeframe === '1Y') {
      timeStr = `Day ${i + 1}`;
    }

    points.push({
      time: timeStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentClose = close;
  }

  return points;
}
